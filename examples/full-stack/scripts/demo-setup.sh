#!/usr/bin/env bash
# One-time local setup for the demo. Safe to run again: existing files are kept.
#
#   pds.secrets.env   PDS secrets                              (gitignored)
#   .local/oem.pem    Ed25519 OEM signing key (private)        (gitignored)
#   .env              what docker compose needs from the above (gitignored)
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
need_tools openssl base64

"${ROOT}/scripts/gen-pds-secrets.sh"

mkdir -p "$LOCAL"
if [[ ! -f "$OEM_KEY_FILE" ]]; then
  (umask 077 && openssl genpkey -algorithm ed25519 -out "$OEM_KEY_FILE")
  echo "wrote ${OEM_KEY_FILE} (OEM signing key — stays on the publisher's machine)"
else
  echo "exists: ${OEM_KEY_FILE} (not overwriting)"
fi

PUB="$(oem_public_key "$OEM_KEY_FILE")"
[[ ${#PUB} -eq 43 ]] || die "could not derive the OEM public key from ${OEM_KEY_FILE}"

# Sidekar gets only the PUBLIC key. The walkthrough container plays the
# publisher's workstation in the browser demo, so it is handed the private key.
(
  umask 077
  {
    echo "# Generated by scripts/demo-setup.sh — local demo only, do not commit."
    echo "OFW_TRUSTED_OEM_KEYS=${PUB}"
    echo "OFW_OEM_KEY_B64=$(base64 <"$OEM_KEY_FILE" | tr -d '\n')"
  } >"${ROOT}/.env"
)
echo "wrote ${ROOT}/.env"
echo "OEM public key (pinned by Sidekar): ${PUB}"
